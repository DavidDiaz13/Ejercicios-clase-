a = float(input("Ingrese el primer número: "))
b = float(input("Ingrese el segundo número: "))

def sumar(a, b):
    return a + b
print(sumar(a, b))

def restar(a, b):
    return a - b
print(restar(a, b))

def multiplicar(a, b):
    return a * b
print(multiplicar(a, b))

def dividir(a, b):
    return a / b
print(dividir(a, b))

def potencia(base, exponente):
    return base ** exponente
print(potencia(a, b))